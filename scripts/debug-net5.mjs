import { chromium } from 'playwright';
import { config as loadEnv } from 'dotenv';
import { resolve } from 'node:path';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
loadEnv({ path: resolve(process.cwd(), '.env.local') });
const BASE = process.env.E2E_BASE_URL ?? 'http://localhost:4200';
const userDataDir = mkdtempSync(tmpdir() + '/pw-');
const context = await chromium.launchPersistentContext(userDataDir, { viewport: { width: 1440, height: 900 }, bypassServiceWorker: true });
const page = await context.newPage();
await page.goto(`${BASE}/login`, { waitUntil: 'domcontentloaded' });
await page.waitForSelector('#identifier', { state: 'visible', timeout: 60000 });
await page.fill('#identifier', process.env.E2E_ADMIN_EMAIL);
await page.fill('#password', process.env.E2E_ADMIN_PASSWORD);
const response = page.waitForResponse((r) => r.url().includes('/api/auth/login') && r.request().method() === 'POST');
await page.click('button[type="submit"]');
await response;
await page.waitForURL('**/dashboard', { timeout: 20000 });
await page.goto(`${BASE}/dashboard/users/1?v=${Date.now()}`, { waitUntil: 'networkidle' });
await page.waitForTimeout(5000);
const txt = await page.locator('body').innerText();
const lines = txt.split('\n').map(l=>l.trim()).filter(Boolean);
const idx = lines.findIndex(l => /Manage|Change role/i.test(l));
console.log('lines:', lines.slice(Math.max(0,idx-2), idx+3));
await context.close();
