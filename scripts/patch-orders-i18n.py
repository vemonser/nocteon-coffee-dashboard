    for path, section, statuses in ((EN, EN_ORDERS, "en"), (AR, AR_ORDERS, "ar")):
        data = load(path)
        data["orders"] = section
        # The badge component needs a label for the two new kinds.
        data["common"]["statuses"]["confirmed"] = "Confirmed" if statuses == "en" else "مؤكد"
        data["common"]["statuses"]["unknown"] = "Unknown" if statuses == "en" else "غير معروف"
        save(path, data)
        print(f"patched {path.name}")


