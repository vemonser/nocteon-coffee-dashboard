// Raw-control scanner — MUST mirror the scan rules in
// src/app/core/design/raw-controls.spec.ts (that spec is the source of truth and
// fails when a NEW raw control appears). This script regenerates the baseline
// it reads. Run from the repo root:  node scripts/raw-control-scan.mjs --write
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = 'src/app';
const OUT = 'src/app/core/design/raw-controls.baseline.json';

// A control is "raw" when it is a native control that does not carry its helm
// directive. `hlm-native-select` is a component (not a raw <select>), and
// type="hidden" is not a control.
//
// TEMPORARY: `<input class="table-check">` is exempt — see the header note in
// raw-controls.spec.ts. Phase 5 deletes the exemption along with the CSS.
const HELM_ATTR = { input: 'hlmInput', select: null, button: 'hlmBtn' };

export function scanRawControls(source) {
  const counts = { input: 0, select: 0, button: 0, tableCheck: 0 };
  // Comments are prose, not markup — same rule as raw-controls.spec.ts.
  const markup = source.replace(/<!--[\s\S]*?-->/g, '');
  const re = /<(input|select|button)(?=[\s/>])/g;
  let m;
  while ((m = re.exec(markup)) !== null) {
    const tag = m[1];
    // find the end of the tag, respecting quoted attribute values
    let i = m.index + m[0].length;
    let quote = null;
    while (i < markup.length) {
      const c = markup[i];
      if (quote) { if (c === quote) quote = null; }
      else if (c === '"' || c === "'") quote = c;
      else if (c === '>') break;
      i++;
    }
    const attrs = markup.slice(m.index, i + 1);
    if (tag === 'input' && /\stype\s*=\s*["']hidden["']/.test(attrs)) continue;
    if (tag === 'input' && /\sclass\s*=\s*["'][^"']*\btable-check\b/.test(attrs)) {
      counts.tableCheck++;
      continue;
    }
    const need = HELM_ATTR[tag];
    if (need === null) { counts[tag]++; continue; }
    if (!new RegExp(`\\s${need}(?=[\\s/>=]|$)`).test(attrs)) counts[tag]++;
  }
  return counts;
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (entry.endsWith('.html')) out.push(p);
  }
  return out;
}

const files = walk(ROOT).sort();
const baseline = {};
let totals = { input: 0, select: 0, button: 0, tableCheck: 0 };
for (const f of files) {
  const counts = scanRawControls(readFileSync(f, 'utf8'));
  totals = {
    input: totals.input + counts.input,
    select: totals.select + counts.select,
    button: totals.button + counts.button,
    tableCheck: totals.tableCheck + counts.tableCheck,
  };
  if (counts.input + counts.select + counts.button === 0) continue;
  baseline[relative('.', f)] = { input: counts.input, select: counts.select, button: counts.button };
}

const doc = {
  _comment:
    'Phase 0.4 ratchet. Generated by scripts/raw-control-scan.mjs — see raw-controls.spec.ts. Counts may only shrink. `<input class="table-check">` is a TEMPORARY exemption (Phase 5) and is not counted here: it is reported separately by the spec.',
  ...baseline,
};
if (process.argv.includes('--write')) {
  writeFileSync(OUT, JSON.stringify(doc, null, 2) + '\n');
  console.log('wrote', OUT);
}
console.log('files with raw controls:', Object.keys(baseline).length, 'of', files.length, 'templates');
console.log('totals:', JSON.stringify(totals), '(tableCheck is excluded from the ratchet)');
